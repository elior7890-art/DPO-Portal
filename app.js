/* ---------------- main render ---------------- */

function render() {
  const root = document.getElementById("root");
  let html;
  if (state.screen === "login") html = renderLogin();
  else if (state.screen === "login-dpo") html = renderLoginDpo();
  else if (state.screen === "clients") html = renderNav() + renderClients();
  else if (state.screen === "admin") html = isDpo() ? renderNav() + renderAdmin() : renderNav() + renderClients();
  else html = renderNav() + renderProject();

  if (state.consent) html += renderConsentGate();
  root.innerHTML = html;

  if (state.screen === "project") wireProjectTabs();
  if (state.consent) wireConsentGate();
}

/* ---------------- post-render wiring (keyboard nav, focus trap, scroll) ---------------- */

function wireProjectTabs() {
  const list = document.getElementById("project-tablist");
  if (!list) return;
  list.onkeydown = e => {
    const keys = { ArrowRight: -1, ArrowLeft: 1, Home: "first", End: "last" };
    const move = keys[e.key];
    if (move === undefined) return;
    e.preventDefault();
    const defs = tabDefs(), at = defs.findIndex(t => t[0] === state.tab);
    const next = move === "first" ? 0 : move === "last" ? defs.length - 1 : (at + move + defs.length) % defs.length;
    state.tab = defs[next][0];
    render();
    const btn = document.querySelectorAll('#project-tablist [role="tab"]')[next];
    if (btn) btn.focus();
  };
}

function wireConsentGate() {
  const dialog = document.getElementById("consent-dialog");
  const pane = document.getElementById("consent-pane");
  if (!dialog || !pane) return;

  if (!consentFocused) {
    const firstTab = dialog.querySelector('[role="tab"][aria-selected="true"]');
    if (firstTab) firstTab.focus();
    consentFocused = true;
  }

  dialog.onkeydown = e => {
    if (e.key === "ArrowRight" || e.key === "ArrowLeft") {
      if (!e.target.matches('[role="tab"]')) return;
      e.preventDefault();
      state.consentTab = state.consentTab === "terms" ? "privacy" : "terms";
      render();
      const el = document.getElementById("tab-" + state.consentTab);
      if (el) el.focus();
      return;
    }
    if (e.key !== "Tab") return;
    const items = Array.prototype.filter.call(
      dialog.querySelectorAll('button, [href], input, select, textarea, [tabindex]:not([tabindex="-1"])'),
      el => !el.disabled && el.offsetParent !== null
    );
    if (!items.length) return;
    const first = items[0], last = items[items.length - 1];
    if (!e.shiftKey && document.activeElement === last) { e.preventDefault(); first.focus(); }
    if (e.shiftKey && document.activeElement === first) { e.preventDefault(); last.focus(); }
  };

  const markReadIfAtBottom = () => {
    if (pane.scrollTop + pane.clientHeight < pane.scrollHeight - 24) return;
    const key = state.consentTab === "terms" ? "readTerms" : "readPrivacy";
    if (state[key]) return;
    const savedTop = pane.scrollTop;
    state[key] = true;
    render();
    const newPane = document.getElementById("consent-pane");
    if (newPane) newPane.scrollTop = savedTop;
  };

  pane.onscroll = markReadIfAtBottom;
  // on a tall screen the whole document can fit without any overflow, so no
  // "scroll" event ever fires — treat that as already having read it.
  markReadIfAtBottom();
}

