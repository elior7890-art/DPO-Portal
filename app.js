function visibleQuestions(part) { return part.questions.filter(q => !q.when || q.when()); }

function isAnswered(q) {
  const answer = answerOf(q.id);
  return q.type === "multi" ? !!(answer && answer.length) : !!answer;
}

function impactOf(q) {
  if (q.impactFn) return q.impactFn();
  if (q.type === "multi") {
    const relevant = (answerOf(q.id) || []).filter(v => q.impactAny.unless.indexOf(v) < 0);
    return relevant.length ? { text: q.impactAny.text, alert: false } : null;
  }
  const key = answerOf(q.id);
  return (q.impact || []).filter(r => r.eq === key).map(r => ({ text: r.text, alert: !!r.alert }))[0] || null;
}

