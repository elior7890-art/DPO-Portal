function handleAction(action, el) {
  if (action === "go-login-dpo") state.screen = "login-dpo";
  else if (action === "go-login-client") state.screen = "login";
  else if (action === "reset-consent") { try { localStorage.removeItem(CONSENT_KEY); } catch (e) {} }
  else if (action === "logout") state.screen = isDpo() ? "login-dpo" : "login";
  else if (action === "go-clients") state.screen = "clients";
  else if (action === "go-admin") { if (isDpo()) state.screen = "admin"; }
  else if (action === "open-project") { state.screen = "project"; state.tab = "overview"; }
  else if (action === "set-tab") state.tab = el.dataset.tab;
  else if (action === "set-role") {
    const r = el.dataset.role;
    state.role = r;
    if (r === "client") {
      state.screen = "project";
      if (state.tab === "private") state.tab = "overview";
    }
  }
  else if (action === "open-new-org") state.adminForm = "org";
  else if (action === "open-new-user") state.adminForm = "user";
  else if (action === "close-admin-form") state.adminForm = "user";
  else if (action === "consent-tab") state.consentTab = el.dataset.tab;
  else if (action === "accept-consent") {
    if (!(state.okTerms && state.okPrivacy)) return;
    try { localStorage.setItem(CONSENT_KEY, new Date().toISOString()); } catch (e) {}
    state.consent = false;
  }
  else if (action === "q-part") state.qPart = el.dataset.part;
  else if (action === "q-prev" || action === "q-next") {
    const parts = getParts();
    const at = Math.max(0, parts.findIndex(p => p.id === state.qPart));
    const next = action === "q-prev" ? Math.max(0, at - 1) : Math.min(parts.length - 1, at + 1);
    state.qPart = parts[next].id;
  }
  else if (action === "q-ask-advisor") state.tab = "chat";
  render();
}

const root = document.getElementById("root");

root.addEventListener("click", e => {
  const el = e.target.closest("[data-action]");
  if (!el) return;
  handleAction(el.dataset.action, el);
});

root.addEventListener("change", e => {
  const el = e.target;
  if (el.matches("input[data-qid]")) {
    const qid = el.dataset.qid, value = el.dataset.value, multi = el.dataset.multi === "1";
    if (multi) {
      const cur = state.answers[qid] || [];
      state.answers[qid] = cur.indexOf(value) >= 0 ? cur.filter(v => v !== value) : cur.concat([value]);
    } else {
      state.answers[qid] = value;
    }
    render();
  } else if (el.matches("input[data-newrole]")) {
    state.newRole = el.dataset.newrole;
    render();
  } else if (el.matches("input[data-consent]")) {
    const which = el.dataset.consent;
    if (which === "terms" && state.readTerms) state.okTerms = !state.okTerms;
    if (which === "privacy" && state.readPrivacy) state.okPrivacy = !state.okPrivacy;
    render();
  }
});

root.addEventListener("input", e => {
  if (e.target.id === "new-user-email") {
    state.email = e.target.value;
    state.emailTouched = true;
    updateEmailValidationUI();
  }
});

root.addEventListener("submit", e => {
  e.preventDefault();
  const form = e.target;
  if (form.id === "login-client-form") doLoginClient();
  else if (form.id === "login-dpo-form") doLoginDpo();
  else if (form.id === "user-form") { state.emailTouched = true; render(); return; }
  else if (form.id === "org-form") return; // demo only, no-op
  render();
});

render();
